#!/usr/bin/env python3
# NFSU: build the AMD FSR 3.1 upscaler compute passes for d3d9_nfsu_fsr.cpp.
#
# Source: AMD FidelityFX SDK v1.1.4 (MIT, sdk/LICENSE.txt) - the GPU headers of include/FidelityFX/gpu and the
# Vulkan pass entry points of src/backends/vk/shaders/fsr3upscaler, copied unmodified into sdk/. v1.1.4 is the
# last SDK with a Vulkan backend / GLSL passes (v2.x is DX12-only, prebuilt signed DLLs).
#
# The SDK's own shader build (FidelityFX_SC.exe, Windows/DXC/ATL only) is replaced by this script + the
# distro glslangValidator. Patches, applied to a generated copy of ffx_fsr3upscaler_callbacks_glsl.h (gen/):
#   1. no separate samplers: DXVK's built-in pipeline layouts have no VK_DESCRIPTOR_TYPE_SAMPLER (only its
#      global sampler heap), so every textureLod(sampler2D(t, s_LinearClamp), uv, lod) becomes a manual
#      clamp-to-edge bilinear from 4 texelFetch (nfsuTextureLod); s_PointClamp was never sampled.
#      The bindings are then contiguous 0..N-1 = DXVK's "binding index = position in the list".
#   2. rw_luma_history: the GLSL declares rgba8 but the SDK creates the image R16G16B16A16_FLOAT (DX12 uses an
#      untyped float4 UAV) - declared rgba16f here so the storage format matches the image (Vulkan rule).
#   3. rw_upscaled_output ("app controlled format", i.e. written without format): declared rgba16f = our output
#      (NFSU_CreateStorageTexture), so no pass needs StorageImageWriteWithoutFormat (DXVK 3.x does not enable
#      that feature; it would rest on the driver's per-format STORAGE_WRITE_WITHOUT_FORMAT bit).
# One fixed permutation (what the game-side mod feeds): HDR colour, render-res (= "low res") motion vectors, no jitter
# in the MVs, standard (non-inverted) depth, reference Lanczos (no LUT), fp32 (FFX_HALF=0) + fp16 copies (_h, FFX_HALF=1).
# Variants: accumulate with/without the RCAS sharpen split, SPD pyramids with/without subgroup quad ops.
#
# Output: nfsu_fsr_spv.h (SPIR-V arrays + per-pass descriptor type tables). Run from this directory:
#   python3 gen_fsr.py
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SDK = os.path.join(HERE, "sdk")
GEN = os.path.join(HERE, "gen")
CB = "fsr3upscaler/ffx_fsr3upscaler_callbacks_glsl.h"

BILINEAR = r'''
// NFSU (gen_fsr.py): manual bilinear, clamp to edge (no separate samplers in DXVK built-in layouts)
FfxFloat32x4 nfsuTextureLod(texture2D t, FfxFloat32x2 uv, FfxFloat32 lod)
{
    FfxInt32 l = FfxInt32(lod);
    FfxInt32x2 sz = textureSize(t, l);
    FfxFloat32x2 p = uv * FfxFloat32x2(sz) - 0.5;
    FfxFloat32x2 fl = floor(p);
    FfxFloat32x2 f = p - fl;
    FfxInt32x2 i0 = clamp(FfxInt32x2(fl), FfxInt32x2(0, 0), sz - 1);
    FfxInt32x2 i1 = clamp(FfxInt32x2(fl) + 1, FfxInt32x2(0, 0), sz - 1);
    FfxFloat32x4 a = texelFetch(t, FfxInt32x2(i0.x, i0.y), l), b = texelFetch(t, FfxInt32x2(i1.x, i0.y), l);
    FfxFloat32x4 c = texelFetch(t, FfxInt32x2(i0.x, i1.y), l), d = texelFetch(t, FfxInt32x2(i1.x, i1.y), l);
    return mix(mix(a, b, f.x), mix(c, d, f.x), f.y);
}
'''

def patch_callbacks():
    src = open(os.path.join(SDK, CB)).read()
    n0 = src.count("s_LinearClamp")
    src, nd = re.subn(r"^layout \(set = 0, binding = 100[01]\) uniform sampler s_(Point|Linear)Clamp;\s*$", "", src, flags=re.M)
    src, ns = re.subn(r"textureLod\(sampler2D\((\w+), s_LinearClamp\),", r"nfsuTextureLod(\1,", src)
    src, nl = re.subn(r"(binding = FSR3UPSCALER_BIND_UAV_LUMA_HISTORY, )rgba8(\))", r"\1rgba16f\2", src)
    src, no = re.subn(r"(binding = FSR3UPSCALER_BIND_UAV_UPSCALED_OUTPUT) /\* app controlled format \*/\)", r"\1, rgba16f)", src)
    inc = '#include "ffx_core.h"\n#endif // #if defined(FFX_GPU)\n'
    assert inc in src, "ffx_core include not found"
    src = src.replace(inc, inc + "\n#if defined(FFX_GPU)" + BILINEAR + "#endif\n", 1)
    left = len(re.findall(r"s_(Linear|Point)Clamp", src))
    assert nd == 2 and ns == n0 - 1 and nl == 1 and no == 1 and left == 0, (nd, ns, n0, nl, no, left)
    os.makedirs(os.path.join(GEN, "fsr3upscaler"), exist_ok=True)
    open(os.path.join(GEN, CB), "w").write("// GENERATED by gen_fsr.py from sdk/" + CB + " - do not edit\n" + src)
    return ns

BASE = ["-DFFX_GPU=1", "-DFFX_GLSL=1", "-DFFX_HALF=0",
        "-DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0",
        "-DFFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0",
        "-DFFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1",
        "-DFFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0",
        "-DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2",
        "-DFFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE=0",
        "-DFFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT=1",
        "-DFFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1",
        "-DFFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS=0",
        "-DFFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH=0"]

# (C name, pass file, extra defines)
PASSES = [
    ("prepare_inputs",          "prepare_inputs",          []),
    ("luma_pyramid",            "luma_pyramid",            []),
    ("luma_pyramid_nowave",     "luma_pyramid",            ["-DFFX_SPD_NO_WAVE_OPERATIONS=1"]),
    ("shading_change_pyramid",  "shading_change_pyramid",  []),
    ("shading_change_pyramid_nowave", "shading_change_pyramid", ["-DFFX_SPD_NO_WAVE_OPERATIONS=1"]),
    ("shading_change",          "shading_change",          []),
    ("prepare_reactivity",      "prepare_reactivity",      []),
    ("luma_instability",        "luma_instability",        []),
    ("accumulate",              "accumulate",              ["-DFFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING=0"]),
    ("accumulate_sharpen",      "accumulate",              ["-DFFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING=1"]),
    ("rcas",                    "rcas",                    []),
    ("debug_view",              "debug_view",              []),
]

def reflect(spv):
    dis = subprocess.run(["spirv-dis", "--raw-id", spv], capture_output=True, text=True, check=True).stdout
    names = dict(re.findall(r'OpName %(\d+) "([^"]*)"', dis))
    bind = dict(re.findall(r"OpDecorate %(\d+) Binding (\d+)", dis))
    types = {m.group(1): (m.group(2), m.group(3).split()) for m in re.finditer(r"%(\d+) = (OpType\w+)(.*)", dis)}
    ptr = {m.group(1): m.group(3) for m in re.finditer(r"%(\d+) = OpTypePointer (\w+) %(\d+)", dis)}
    caps = [c for c in re.findall(r"OpCapability (\w+)", dis) if c != "Shader"]
    ls = tuple(int(x) for x in re.search(r"OpExecutionMode %\d+ LocalSize (\d+) (\d+) (\d+)", dis).groups())
    out = {}
    for m in re.finditer(r"%(\d+) = OpVariable %(\d+) (\w+)", dis):
        vid, pt, sc = m.groups()
        if vid not in bind:
            continue
        kind, args = types[ptr[pt]]
        if kind == "OpTypeImage":
            t = "STORAGE_IMAGE" if args[5] == "2" else "SAMPLED_IMAGE"
        elif kind == "OpTypeStruct" and sc == "Uniform":
            t = "UNIFORM_BUFFER"
        else:
            raise SystemExit(f"{spv}: unexpected binding type {kind} {sc}")
        b = int(bind[vid])
        assert b not in out
        out[b] = (t, names.get(vid, "?"))
    assert sorted(out) == list(range(len(out))), f"{spv}: bindings not contiguous {sorted(out)}"
    return [out[i] for i in range(len(out))], caps, ls

def main():
    ns = patch_callbacks()
    tmp = tempfile.mkdtemp(prefix="nfsu_fsr_")
    lines = ["// GENERATED by gen_fsr.py (AMD FidelityFX SDK v1.1.4 FSR 3.1 upscaler, MIT) - do not edit", "#pragma once",
             "#include <cstdint>", "", "namespace dxvk::nfsu_fsr {", ""]
    table = []
    # every pass twice: fp32 and fp16 ("_h", FFX_HALF=1: Float16/Int16 arithmetic; used only when DXVK enabled shaderFloat16)
    for cname, pfile, extra in [(c, f, e) for c, f, e in PASSES] + [(c + "_h", f, e + ["-DFFX_HALF=1"]) for c, f, e in PASSES]:
        src = os.path.join(SDK, "passes", f"ffx_fsr3upscaler_{pfile}_pass.glsl")
        spv = os.path.join(tmp, cname + ".spv")
        base = [d for d in BASE if not (d.startswith("-DFFX_HALF=") and any(e.startswith("-DFFX_HALF=") for e in extra))]
        cmd = ["glslangValidator", "-V", "--target-env", "vulkan1.1", "-S", "comp"] + base + extra + \
              ["-I" + GEN, "-I" + SDK, "-I" + os.path.join(SDK, "fsr3upscaler"), src, "-o", spv]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"{cname}: glslang failed\n{r.stdout}{r.stderr}")
        subprocess.run(["spirv-val", "--target-env", "vulkan1.1", spv], check=True)
        binds, caps, ls = reflect(spv)
        subprocess.run(["spirv-opt", "--strip-debug", spv, "-o", spv], check=True)   # names only needed by reflect()
        subprocess.run(["spirv-val", "--target-env", "vulkan1.1", spv], check=True)
        words = open(spv, "rb").read()
        assert len(words) % 4 == 0
        w = [int.from_bytes(words[i:i + 4], "little") for i in range(0, len(words), 4)]
        lines.append(f"// {cname}: local size {ls[0]}x{ls[1]}x{ls[2]}, capabilities: {' '.join(caps) or '-'}")
        lines.append("//   " + ", ".join(f"{i}:{n}" for i, (t, n) in enumerate(binds)))
        lines.append(f"static const uint32_t {cname}_spv[] = {{")
        for i in range(0, len(w), 8):
            lines.append("  " + ", ".join(f"0x{x:08x}" for x in w[i:i + 8]) + ",")
        lines.append("};")
        lines.append(f"static const VkDescriptorType {cname}_types[] = {{ " +
                     ", ".join("VK_DESCRIPTOR_TYPE_" + t for t, n in binds) + " };")
        lines.append("")
        table.append((cname, len(binds), ls, caps, len(words)))
        print(f"{cname:32s} {len(words):6d} bytes  {len(binds):2d} bindings  local {ls}  caps {' '.join(caps) or '-'}")
    lines.append("}")
    open(os.path.join(HERE, "nfsu_fsr_spv.h"), "w").write("\n".join(lines) + "\n")
    print(f"callbacks: {ns} linear samples -> nfsuTextureLod; nfsu_fsr_spv.h written ({len(table)} modules)")

if __name__ == "__main__":
    main()
